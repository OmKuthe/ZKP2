// frontend-web/src/pages/FlaggedSessions.jsx
import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import api from '../api/client';
import { SeverityBadge, StatusBadge } from '../components/AnomalyBadge';

const FlaggedSessions = () => {
  const [anomalies, setAnomalies] = useState([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  const [statusFilter, setStatusFilter] = useState('open');
  const [severityFilter, setSeverityFilter] = useState('');
  const [typeFilter, setTypeFilter] = useState('');

  const fetchAnomalies = async () => {
    setLoading(true);
    setError('');
    try {
      const params = new URLSearchParams();
      if (statusFilter) params.append('status', statusFilter);
      if (severityFilter) params.append('severity', severityFilter);
      if (typeFilter) params.append('type', typeFilter);
      params.append('limit', '200');

      const res = await api.get(`/v2/anomalies?${params.toString()}`);
      setAnomalies(res.data.anomalies || []);
      setTotal(res.data.total || 0);
    } catch (err) {
      setError(err.response?.data?.detail || err.message || 'Failed to load anomalies');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAnomalies();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [statusFilter, severityFilter, typeFilter]);

  return (
    <div>
      <div className="flex justify-between items-center mb-6">
        <div>
          <h1 className="text-2xl font-bold text-slate-800">Flagged Sessions</h1>
          <p className="text-sm text-slate-500">
            Anomalies generated by the verification pipeline
          </p>
        </div>
        <button onClick={fetchAnomalies} className="btn-secondary text-sm">
          ↻ Refresh
        </button>
      </div>

      <div className="card mb-4 flex flex-wrap gap-3 items-center">
        <div>
          <label className="text-xs font-medium text-slate-500 mr-2">Status</label>
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="px-3 py-1.5 border border-slate-300 rounded-lg text-sm"
          >
            <option value="open">Open</option>
            <option value="reviewed">Reviewed</option>
            <option value="dismissed">Dismissed</option>
            <option value="resolved">Resolved</option>
            <option value="">All</option>
          </select>
        </div>
        <div>
          <label className="text-xs font-medium text-slate-500 mr-2">Severity</label>
          <select
            value={severityFilter}
            onChange={(e) => setSeverityFilter(e.target.value)}
            className="px-3 py-1.5 border border-slate-300 rounded-lg text-sm"
          >
            <option value="">All</option>
            <option value="low">Low</option>
            <option value="medium">Medium</option>
            <option value="high">High</option>
            <option value="critical">Critical</option>
          </select>
        </div>
        <div>
          <label className="text-xs font-medium text-slate-500 mr-2">Type</label>
          <select
            value={typeFilter}
            onChange={(e) => setTypeFilter(e.target.value)}
            className="px-3 py-1.5 border border-slate-300 rounded-lg text-sm"
          >
            <option value="">All</option>
            <option value="environment_mismatch">Wi-Fi Mismatch</option>
            <option value="continuity_gap">Heartbeat Gap</option>
            <option value="reverify_timeout">Re-verify Timeout</option>
          </select>
        </div>
        <div className="ml-auto text-sm text-slate-500">
          {total} anomaly{total === 1 ? '' : 'ies'}
        </div>
      </div>

      {error && (
        <div className="card mb-4 bg-danger-500 text-white">{error}</div>
      )}

      <div className="card">
        {loading ? (
          <div className="flex justify-center py-12">
            <div className="animate-spin rounded-full h-10 w-10 border-b-2 border-primary-500" />
          </div>
        ) : anomalies.length === 0 ? (
          <p className="text-center text-slate-400 py-12">
            No anomalies match the current filters.
          </p>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-slate-200">
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Student</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Company</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Type</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Severity</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Status</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Detected</th>
                  <th className="text-left py-2 px-3 text-slate-500 font-medium">Actions</th>
                </tr>
              </thead>
              <tbody>
                {anomalies.map((a) => (
                  <tr key={a.id} className="border-b border-slate-100 hover:bg-slate-50">
                    <td className="py-2 px-3">
                      <div className="font-medium text-slate-700">{a.student_name || '—'}</div>
                      <div className="text-xs text-slate-400">{a.student_code}</div>
                    </td>
                    <td className="py-2 px-3 text-slate-600">{a.company_name || '—'}</td>
                    <td className="py-2 px-3 text-slate-600">{a.type}</td>
                    <td className="py-2 px-3"><SeverityBadge severity={a.severity} /></td>
                    <td className="py-2 px-3"><StatusBadge status={a.status} /></td>
                    <td className="py-2 px-3 text-xs text-slate-500">
                      {a.detected_at ? new Date(a.detected_at).toLocaleString() : '—'}
                    </td>
                    <td className="py-2 px-3">
                      {a.session_uuid ? (
                        <Link
                          to={`/manager/sessions/${a.session_uuid}`}
                          className="text-primary-500 hover:underline text-sm"
                        >
                          View session →
                        </Link>
                      ) : (
                        <span className="text-slate-400 text-sm">—</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
};

export default FlaggedSessions;